#!/usr/bin/env python3
"""
aggregate_coverage.py — Parse URG coverage report and print missing bins.

Reads the text report generated by:
    urg -dir sim/vcs/cov.vdb -format text -report <dir>

Outputs:
  - Console table of covergroup coverage percentages
  - List of uncovered bins
  - Optional HTML dashboard (no external libraries)

Usage:
    python scripts/aggregate_coverage.py \
        --urg-report sim/vcs/coverage_report \
        --threshold 95 \
        --html sim/vcs/coverage_dashboard.html
"""

import argparse
import os
import re
import sys
from dataclasses import dataclass, field
from pathlib import Path
from typing import List, Optional

# ── Patterns for URG text format ─────────────────────────────────────────────
RE_COVERGROUP = re.compile(r"^Covergroup\s+Coverage\s+Report", re.IGNORECASE)
RE_CG_NAME    = re.compile(r"^\s*(\w+)\s+(\d+\.\d+)%\s+(\d+)/(\d+)")
RE_BIN_LINE   = re.compile(r"^\s+(bins|bin)\s+(\S+)\s+(\d+)\s+(\d+)")
RE_SUMMARY    = re.compile(r"Total\s+Coverage\s+Summary")

# Fallback: simple percentage extraction
RE_PERCENT    = re.compile(r"(\w[\w_]*)\s+([\d.]+)%")


@dataclass
class CoverBin:
    name:  str
    hits:  int
    total: int

    @property
    def covered(self) -> bool:
        return self.hits > 0


@dataclass
class CoverGroup:
    name:       str
    coverage:   float
    hits:       int   = 0
    total:      int   = 0
    bins:       List[CoverBin] = field(default_factory=list)

    @property
    def uncovered_bins(self):
        return [b for b in self.bins if not b.covered]


def parse_urg_text(report_dir: Path) -> List[CoverGroup]:
    """Parse URG text report directory. Returns list of CoverGroup objects."""
    groups = []

    # URG writes a dashboard file and per-covergroup files
    # Look for dashboard.txt or the main coverage.txt
    candidates = list(report_dir.glob("*.txt")) + \
                 list(report_dir.glob("dashboard.txt"))

    all_text = ""
    for f in candidates:
        try:
            all_text += f.read_text(errors="replace") + "\n"
        except Exception:
            pass

    if not all_text:
        print(f"WARNING: No .txt files found in {report_dir}")
        return groups

    # Extract covergroup entries
    current_cg: Optional[CoverGroup] = None
    for line in all_text.splitlines():
        # Match covergroup with percentage
        m = RE_CG_NAME.match(line)
        if m:
            cg_name = m.group(1)
            pct     = float(m.group(2))
            hits    = int(m.group(3))
            total   = int(m.group(4))
            if cg_name.startswith("cg_"):
                current_cg = CoverGroup(name=cg_name, coverage=pct,
                                        hits=hits, total=total)
                groups.append(current_cg)
            continue

        # Match bin line within current covergroup
        mb = RE_BIN_LINE.match(line)
        if mb and current_cg:
            bin_name = mb.group(2)
            bin_hits = int(mb.group(3))
            bin_total= int(mb.group(4))
            current_cg.bins.append(CoverBin(bin_name, bin_hits, bin_total))

    # Fallback: extract any percentage lines
    if not groups:
        for m in RE_PERCENT.finditer(all_text):
            name, pct = m.group(1), float(m.group(2))
            if name.startswith("cg_") or name.startswith("cp_"):
                groups.append(CoverGroup(name=name, coverage=pct))

    return groups


def print_coverage_table(groups: List[CoverGroup], threshold: float) -> None:
    col_w = 35
    print(f"\n{'='*65}")
    print(f"  {'Covergroup':<{col_w}} {'Coverage':>10}  {'Status'}")
    print(f"  {'-'*col_w}  {'-'*10}  {'-'*8}")

    for g in sorted(groups, key=lambda x: x.coverage):
        bar_len = int(g.coverage / 5)
        bar     = "█" * bar_len + "░" * (20 - bar_len)
        color   = "\033[32m" if g.coverage >= threshold else \
                  "\033[33m" if g.coverage >= 80 else "\033[31m"
        reset   = "\033[0m"
        status  = "OK" if g.coverage >= threshold else "BELOW TARGET"
        print(f"  {g.name:<{col_w}} {color}{g.coverage:>6.1f}%{reset}  {status}")

    if groups:
        avg = sum(g.coverage for g in groups) / len(groups)
        print(f"  {'-'*col_w}  {'-'*10}")
        overall_color = "\033[32m" if avg >= threshold else "\033[31m"
        print(f"  {'AVERAGE':<{col_w}} {overall_color}{avg:>6.1f}%\033[0m")
    print(f"{'='*65}\n")


def print_uncovered_bins(groups: List[CoverGroup]) -> None:
    missing = [(g, b) for g in groups for b in g.uncovered_bins]
    if not missing:
        print("  All bins covered! ✓\n")
        return

    print(f"  Uncovered bins ({len(missing)} total):\n")
    print(f"  {'Covergroup':<30}  {'Bin':<30}")
    print(f"  {'-'*30}  {'-'*30}")
    for g, b in sorted(missing, key=lambda x: x[0].name):
        print(f"  {g.name:<30}  {b.name:<30}  → add directed test")
    print()


def build_html_dashboard(groups: List[CoverGroup], threshold: float) -> str:
    rows = ""
    for g in sorted(groups, key=lambda x: -x.coverage):
        color = "#2ecc71" if g.coverage >= threshold else \
                "#e67e22" if g.coverage >= 80 else "#e74c3c"
        rows += f"""
        <tr>
          <td><code>{g.name}</code></td>
          <td>
            <div class="bar-bg">
              <div class="bar-fill" style="width:{g.coverage:.1f}%;background:{color}"></div>
            </div>
          </td>
          <td style="color:{color};font-weight:700">{g.coverage:.1f}%</td>
          <td>{'✓' if g.coverage >= threshold else '✗'}</td>
        </tr>"""

    avg = sum(g.coverage for g in groups) / len(groups) if groups else 0.0
    avg_color = "#2ecc71" if avg >= threshold else "#e74c3c"

    return f"""<!DOCTYPE html>
<html><head><meta charset="utf-8">
<title>RV32IM Coverage Dashboard</title>
<style>
  body {{ font-family: monospace; background:#0D1117; color:#DCE4F0;
         padding:32px; max-width:900px; margin:auto; }}
  h1   {{ color:#E8A030; font-size:20px; border-bottom:2px solid #E8A030;
         padding-bottom:8px; }}
  .avg {{ font-size:36px; color:{avg_color}; font-weight:700; margin:16px 0; }}
  table{{ width:100%; border-collapse:collapse; font-size:13px; }}
  th   {{ text-align:left; padding:8px 12px; background:#1A2035;
         color:#7A8BAA; font-size:11px; letter-spacing:.1em;
         text-transform:uppercase; }}
  td   {{ padding:8px 12px; border-bottom:1px solid #2A3550; }}
  .bar-bg  {{ background:#1A2035; border-radius:3px; height:14px; }}
  .bar-fill{{ height:14px; border-radius:3px; transition:width .3s; }}
</style></head><body>
<h1>RV32IM UVM — Functional Coverage Dashboard</h1>
<div class="avg">Average: {avg:.1f}%</div>
<table>
  <thead><tr><th>Covergroup</th><th>Coverage</th><th>%</th><th>Pass</th></tr></thead>
  <tbody>{rows}</tbody>
</table>
</body></html>"""


def main() -> int:
    parser = argparse.ArgumentParser(description="Aggregate URG coverage report")
    parser.add_argument("--urg-report", required=True,
                        help="URG text report directory")
    parser.add_argument("--threshold",  type=float, default=95.0,
                        help="Coverage threshold (default 95%%)")
    parser.add_argument("--html",       default=None,
                        help="Optional HTML dashboard output path")
    args = parser.parse_args()

    report_dir = Path(args.urg_report)
    if not report_dir.exists():
        print(f"ERROR: report directory not found: {report_dir}")
        print("  Run 'make coverage' to generate it first.")
        return 1

    groups = parse_urg_text(report_dir)

    if not groups:
        print("WARNING: No covergroup data found. Check URG report format.")
        return 1

    print_coverage_table(groups, args.threshold)
    print_uncovered_bins(groups)

    # Below-threshold check
    below = [g for g in groups if g.coverage < args.threshold]
    if below:
        print(f"  {len(below)} covergroup(s) below {args.threshold}% threshold:")
        for g in below:
            print(f"    - {g.name}: {g.coverage:.1f}%")
        print()

    # HTML dashboard
    if args.html:
        html_path = Path(args.html)
        html_path.write_text(build_html_dashboard(groups, args.threshold))
        print(f"  HTML dashboard written to {html_path}")

    avg = sum(g.coverage for g in groups) / len(groups) if groups else 0.0
    return 0 if avg >= args.threshold else 1


if __name__ == "__main__":
    sys.exit(main())
